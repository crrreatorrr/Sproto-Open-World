import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

/** The rules that keep the sim pure and co-op possible (plan §2.1–2.2, §8). */
const SRC = path.resolve(__dirname, '../src');

function files(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? files(p) : /\.(ts|tsx)$/.test(e.name) ? [p] : [];
  });
}
const rel = (f: string) => path.relative(SRC, f).split(path.sep).join('/');
/** Source with comments removed, so a rule mentioned in a comment doesn't trip the test. */
const code = (f: string) => fs.readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
const imports = (src: string) => [...src.matchAll(/\bfrom\s+['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g)].map((m) => m[1] ?? m[2]);

const pure = files(path.join(SRC, 'sim')).concat(files(path.join(SRC, 'content')));

describe('architecture', () => {
  it('sim and content use no three.js, DOM, clock, Math.random, storage or timers', () => {
    const banned = [/\bMath\.random\b/, /\bDate\.now\b/, /\bperformance\.now\b/, /\bwindow\./, /\bdocument\./, /\blocalStorage\b/, /\bsetTimeout\b/, /\bsetInterval\b/, /\brequestAnimationFrame\b/];
    for (const f of pure) {
      const src = code(f);
      for (const re of banned) expect(re.test(src), `${rel(f)} uses ${re}`).toBe(false);
      for (const imp of imports(src)) expect(imp === 'three' || imp.startsWith('three/'), `${rel(f)} imports ${imp}`).toBe(false);
    }
  });

  it('Rapier is imported only under sim/physics', () => {
    for (const f of files(SRC)) {
      if (rel(f).startsWith('sim/physics/')) continue;
      for (const imp of imports(code(f))) expect(imp.includes('@dimforge'), `${rel(f)} imports ${imp}`).toBe(false);
    }
  });

  it('the sim never imports render, ui, world, app, audio, input, camera or debug', () => {
    // Top-level client folders only: src/content/world (the shared pure format) is fine.
    const outside = /^(render|ui|world|app|audio|input|camera|debug|assets|workers)\//;
    for (const f of pure) {
      for (const imp of imports(code(f))) {
        if (!imp.startsWith('.')) continue;
        const target = rel(path.resolve(path.dirname(f), imp));
        expect(outside.test(target), `${rel(f)} imports ${target}`).toBe(false);
      }
    }
  });

  it('render, camera and ui see only the ReadonlySimView, never SimWorld', () => {
    for (const f of files(SRC)) {
      if (!/^(render|camera|ui)\//.test(rel(f))) continue;
      for (const imp of imports(code(f))) expect(/SimWorld|physics\/PhysicsWorld$/.test(imp), `${rel(f)} imports ${imp}`).toBe(false);
    }
  });

  it('the loader keeps meshopt decoding and at most 4 parallel requests', () => {
    const src = fs.readFileSync(path.join(SRC, 'assets/AssetLoader.ts'), 'utf8');
    expect(src).toMatch(/setMeshoptDecoder\(MeshoptDecoder\)/);
    expect(src).toMatch(/const PARALLEL = 4;/);
  });

  it('generated content is never hand-edited (carries its generator header)', () => {
    for (const f of files(path.join(SRC, 'content/generated'))) {
      expect(fs.readFileSync(f, 'utf8').startsWith('// Generated by tools/'), rel(f)).toBe(true);
    }
  });
});
