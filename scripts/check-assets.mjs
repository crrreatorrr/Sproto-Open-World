#!/usr/bin/env node
/**
 * Asset gates (plan §3.5, §7.3): triangle caps by folder tier (props 4k, landmarks 10k), the
 * player's clip list and its staff socket, that every file under public/assets is tracked
 * (IMPORTED.json, the art pipeline, or a prop LOD1 generated from a tracked LOD0) and that every
 * world prop has its LOD1; the M4 models' clips and the chest's lid node.
 */
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { MeshoptDecoder } from 'meshoptimizer';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('public/assets');
/**
 * World props that are landmarks or set pieces (plan §3.5: landmarks ≤ 10k triangles, other props
 * ≤ 4k). Matched by file name under models/props/, LOD0 and LOD1.
 */
/** Environment kits built by this repo (tools/build-env-props.mjs): their files are owned, and their landmarks take the landmark cap. */
const ENV_PROPS_FILE = path.resolve('art/source/env/ENV_PROPS.json');
const ENV_PROPS = fs.existsSync(ENV_PROPS_FILE) ? JSON.parse(fs.readFileSync(ENV_PROPS_FILE, 'utf8')).props : {};
const ENV_LANDMARKS = Object.entries(ENV_PROPS).filter(([, p]) => p.landmark).map(([name]) => name);
const ownedEnvProp = (rel) => {
  const m = /^models\/props\/(.+?)(-lod1)?\.glb$/.exec(rel);
  return Boolean(m && ENV_PROPS[m[1]]);
};
const LANDMARKS = [...ENV_LANDMARKS, 'grove_water_tower', 'grove_tower', 'grove_beanstalk', 'grove_silo', 'skyline_crane', 'frost_beacon', 'frost_gate', 'underworks_hoist'];
/** Triangle caps (plan §3.5, revision 2): 9k standard; 22k elites, bosses, NPCs and the player. */
const CAPS = [
  [new RegExp(`^models/props/(${LANDMARKS.join('|')})(-lod1)?\\.glb$`), 10000],
  [/^models\/characters\/player\.glb$/, 22000],
  [/^models\/(bosses|elites|npcs|mounts)\//, 22000],
  [/^models\/enemies\//, 9000],
  [/^models\/staffs\/.*-lod1\.glb$/, 4000],
  [/^models\/staffs\//, 12000],
  [/^models\/props\//, 4000],
  [/^models\/pickups\//, 1000],
  // M4: shrines and chests (the cartoon kit), as small as props.
  [/^models\/interactables\//, 4000],
];
/** Clips the views play from the M4 models (the importer keeps only these on the villagers). */
const REQUIRED_CLIPS = {
  'models/elites/gatekeeper.glb': ['idle', 'walk', 'run', 'smash'],
  'models/bosses/drake.glb': ['fly', 'fireball'],
  'models/bosses/drake_far.glb': ['fly'],
  'models/bosses/scrapjaw.glb': ['idle', 'walk', 'smash', 'slam', 'charge_start', 'charge', 'stunned', 'roar', 'throw_start', 'throw_loop'],
  ...Object.fromEntries(['pepe_general', 'pepe', 'pepe_tux', 'broccoli', 'agent'].map((id) => [`models/npcs/${id}.glb`, ['idle']])),
};
const PLAYER_CLIPS = ['idle', 'run', 'run_back', 'strafe_l', 'strafe_r', 'jump', 'roll', 'hit', 'stun', 'defeat', 'victory', 'cast', 'cast_big', 'attack_light_1', 'attack_light_2', 'attack_light_3', 'attack_heavy', 'block', 'mount', 'ride', 'dismount'];
/** Files made by this repo's own pipelines (not copied from a sibling). */
const OWN = new Set(['models/characters/player.glb', 'models/characters/player.melee.json', 'models/mounts/pepe_bull.glb', 'models/staffs/staff_rootcleaver.glb', 'IMPORTED.json']);
/**
 * Relic and totem icons. Design expert finals from the approved Higgsfield sheets
 * (relics hf_20261119_155949_8f60c417, totems hf_20261119_160337_090c3573). Not sibling imports,
 * so they are not in IMPORTED.json. 128 px PNG masters and 24 px currentColor SVGs.
 */
const ownedKeepsakeIcon = (rel) => /^icons\/keepsakes\/[a-z0-9-]+\.(png|svg)$/.test(rel);
/** Prop LOD1s are generated by tools/import-sibling-assets.mjs from a tracked LOD0. */
const ownedLod1 = (rel) => /^models\/props\/.+-lod1\.glb$/.test(rel) && Boolean(imported[rel.replace(/-lod1\.glb$/, '.glb')]);

await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const imported = JSON.parse(fs.readFileSync(path.join(ROOT, 'IMPORTED.json'), 'utf8')).files;
let failures = 0;
const fail = (msg) => {
  console.error(`check-assets: ${msg}`);
  failures++;
};

function walk(dir, base = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const rel = base ? `${base}/${e.name}` : e.name;
    return e.isDirectory() ? walk(path.join(dir, e.name), rel) : e.name.startsWith('.') ? [] : [rel];
  });
}

for (const rel of walk(ROOT)) {
  if (!OWN.has(rel) && !imported[rel] && !ownedLod1(rel) && !ownedKeepsakeIcon(rel) && !ownedEnvProp(rel)) fail(`${rel} is not tracked in IMPORTED.json`);
  if (/^models\/props\/[^/]+\.glb$/.test(rel) && !rel.endsWith('-lod1.glb') && !fs.existsSync(path.join(ROOT, rel.replace(/\.glb$/, '-lod1.glb')))) {
    fail(`${rel} has no generated LOD1 (run npm run import:assets)`);
  }
  if (!rel.endsWith('.glb')) continue;
  const doc = await io.read(path.join(ROOT, rel));
  let tris = 0;
  for (const mesh of doc.getRoot().listMeshes()) {
    for (const prim of mesh.listPrimitives()) {
      const idx = prim.getIndices();
      tris += (idx ? idx.getCount() : prim.getAttribute('POSITION').getCount()) / 3;
    }
  }
  const cap = CAPS.find(([re]) => re.test(rel))?.[1];
  if (cap && tris > cap) fail(`${rel}: ${tris} triangles, cap ${cap}`);
  if (REQUIRED_CLIPS[rel]) {
    const names = new Set(doc.getRoot().listAnimations().map((a) => a.getName()));
    const missing = REQUIRED_CLIPS[rel].filter((c) => !names.has(c));
    if (missing.length) fail(`${rel} is missing clips: ${missing.join(', ')}`);
  }
  // ChestView swings this node open (the importer splits the lid off the kit's one-mesh chest).
  if (rel === 'models/interactables/chest.glb' && !doc.getRoot().listNodes().some((n) => n.getName() === 'chest_lid')) fail(`${rel} has no chest_lid node`);
  if (rel === 'models/characters/player.glb') {
    const names = new Set(doc.getRoot().listAnimations().map((a) => a.getName()));
    const missing = PLAYER_CLIPS.filter((c) => !names.has(c));
    if (missing.length) fail(`player.glb is missing clips: ${missing.join(', ')}`);
    const socket = doc.getRoot().listNodes().find((n) => n.getName() === 'socket_staff');
    if (!socket) fail('player.glb has no socket_staff');
    else if (Math.abs(socket.getTranslation()[1]) > 50) fail('player.glb socket_staff is misplaced (run art/tools/build-player-glb.mjs)');
  }
}
if (failures) process.exit(1);
console.log('check-assets: all assets within caps and tracked');
